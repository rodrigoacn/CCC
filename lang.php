// ─── Language detection ───────────────────────────────────────────────────────
function detectLang(): string {
  global $LANGUAGES;
  $codes = array_column($LANGUAGES, 'code');
  if (session_status() === PHP_SESSION_ACTIVE && isset($_SESSION['_lang'])) {
    $l = $_SESSION['_lang'];
    if (in_array($l, $codes)) return $l;
  }
  if (isset($_COOKIE['ce_lang'])) {
    $l = $_COOKIE['ce_lang'];
    if (in_array($l, $codes)) return $l;
  }
  if (isset($_SERVER['HTTP_ACCEPT_LANGUAGE'])) {
    $browser = substr($_SERVER['HTTP_ACCEPT_LANGUAGE'], 0, 2);
    if (in_array($browser, $codes)) return $browser;
  }
  return 'en';
}

function t(string $key, array $params = []): string {
  global $TRANS, $LANGUAGES;
  $lang = detectLang();
  $str = $TRANS[$lang][$key] ?? $TRANS['en'][$key] ?? $TRANS['es'][$key] ?? $key;
  foreach ($params as $k => $v) {
    $str = str_replace('{' . $k . '}', $v, $str);
    $str = str_replace(':' . $k, $v, $str);
  }
  return $str;
}

function ti(string $key, array $params = []): string {
  $text = t($key, $params);
  return 'data-i18n="' . htmlspecialchars($key) . '">' . $text;
}

function setLang(string $code) {
  global $LANGUAGES;
  $codes = array_column($LANGUAGES, 'code');
  if (!in_array($code, $codes)) return;
  if (session_status() === PHP_SESSION_ACTIVE) {
    $_SESSION['_lang'] = $code;
    // Persist to BD if user is logged in
    if (isset($_SESSION['usuarioId']) && function_exists('dbExec')) {
      dbExec("UPDATE usuarios SET idioma_preferido = :lang WHERE usuarioId = :id", ['lang' => $code, 'id' => $_SESSION['usuarioId']]);
    }
  }
  setcookie('ce_lang', $code, time() + 86400 * 30, '/', '', false, false);
}

function renderLangSelector(): string {
  global $LANGUAGES;
  $current = detectLang();
  $html = '<select class="form-select form-select-sm lang-select" id="lang-select" style="background-color:#ffffff;color:#1e293b;border-color:#dbe2ee;font-size:.8rem;" onchange="CE_switchLang(this.value)">';
  foreach ($LANGUAGES as $l) {
    $sel = $l['code'] === $current ? ' selected' : '';
    $html .= '<option value="' . $l['code'] . '"' . $sel . '>' . htmlspecialchars($l['label']) . '</option>';
  }
  $html .= '</select>';
  return $html;
}

function renderTranslationsJSON(): string {
  global $TRANS, $LANGUAGES;
  $out = [];
  foreach ($LANGUAGES as $l) {
    $code = $l['code'];
    $out[$code] = $TRANS[$code] ?? [];
  }
  return json_encode($out, JSON_UNESCAPED_UNICODE | JSON_HEX_TAG | JSON_HEX_AMP);
}

if (!isset($_CE_LANG_API) && isset($_GET['lang'])) {
  setLang($_GET['lang']);
  $url = strtok($_SERVER['REQUEST_URI'], '?');
  $params = $_GET;
  unset($params['lang']);
  if (!empty($params)) {
    $url .= '?' . http_build_query($params);
  }
  header('Location: ' . $url);
  exit;
}

