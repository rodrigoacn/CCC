const ALL: Record<LangCode, Dict> = { es: ES, en: EN, fr: FR, de: DE, pt: PT, it: IT, zh: ZH, ja: JA, ru: RU, ar: AR, hi: HI, ko: KO };

export function translate(lang: LangCode, key: string, params?: Record<string, string | number>): string {
  const dict = ALL[lang] ?? EN;
  let str = dict[key] ?? EN[key] ?? ES[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}
